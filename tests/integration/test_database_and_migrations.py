"""Integration tests for PostgreSQL async sessions, Alembic migrations, and drift detection."""

from __future__ import annotations

import pytest
from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import Column, MetaData, String, Table, text

from mem_ai.core.config import Settings
from mem_ai.db.base import Base
from mem_ai.db.engine import (
    create_async_engine_from_settings,
    create_session_factory,
)
from mem_ai.db.model_registry import load_all_models
from tests.conftest import make_alembic_config


@pytest.mark.integration
@pytest.mark.anyio
async def test_async_engine_uses_utc_timezone_and_pool_settings(
    empty_pg_settings: Settings,
) -> None:
    engine = create_async_engine_from_settings(empty_pg_settings)
    session_factory = create_session_factory(engine)
    try:
        assert engine.pool._pre_ping is True  # type: ignore[attr-defined]
        assert session_factory.kw["expire_on_commit"] is False

        async with session_factory.begin() as session:
            tz = (await session.execute(text("SHOW TIME ZONE"))).scalar_one()
            one = (await session.execute(text("SELECT 1"))).scalar_one()

        assert tz == "UTC"
        assert one == 1
    finally:
        await engine.dispose()


@pytest.mark.integration
def test_empty_database_upgrades_downgrades_and_detects_metadata_drift(
    empty_pg_settings: Settings,
) -> None:
    load_all_models()
    alembic_cfg = make_alembic_config(empty_pg_settings)

    # Upgrade an empty database cleanly, verify no drift, downgrade, and re-upgrade.
    command.upgrade(alembic_cfg, "head")
    command.check(alembic_cfg)
    command.downgrade(alembic_cfg, "base")
    command.upgrade(alembic_cfg, "head")

    # Introduce an unmigrated table in a copy of metadata to verify drift detection fails.
    drifted_metadata = MetaData(naming_convention=Base.metadata.naming_convention)
    Table(
        "unmigrated_drift_probe",
        drifted_metadata,
        Column("id", String(36), primary_key=True),
    )
    drifted_cfg = make_alembic_config(empty_pg_settings)
    drifted_cfg.attributes["target_metadata"] = drifted_metadata

    with pytest.raises(AutogenerateDiffsDetected):
        command.check(drifted_cfg)
